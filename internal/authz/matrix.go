package authz

import (
	"fmt"
	"strings"
)

// AccessMatrix renders built-in role × key × scope type as text (testdata/access-matrix.golden, spec §10): one line
// per role and covered key, with the scope types where a grant of the role at its own scope type makes the key
// effective, and the key's flags (P platform-grantable, E survives the event end, 2F second factor).
func AccessMatrix() string {
	var b strings.Builder
	b.WriteString("# Built-in role × key × scope type (internal/authz, spec §4.4 / Appendix A.2). Generated by TestAccessMatrix -update.\n")
	b.WriteString("# role (granted at) | key | effective at | flags\n")
	for _, role := range builtinRoles {
		for _, k := range role.Expanded() {
			spec, _ := Lookup(k)
			var at []string
			for _, t := range []ScopeType{ScopePlatform, ScopeEvent, ScopeImplicit, ScopePublic} {
				if role.EffectiveAt(k, t) {
					at = append(at, string(t))
				}
			}
			if len(at) == 0 {
				at = []string{"-"}
			}
			var flags []string
			if spec.PlatformGrantable {
				flags = append(flags, "P")
			}
			if spec.SurvivesEventEnd {
				flags = append(flags, "E")
			}
			if spec.SecondFactor {
				flags = append(flags, "2F")
			}
			if len(flags) == 0 {
				flags = []string{"-"}
			}
			fmt.Fprintf(&b, "%s (%s) | %s | %s | %s\n", role.Name, role.Scope, k, strings.Join(at, ","), strings.Join(flags, ","))
		}
	}
	return b.String()
}
