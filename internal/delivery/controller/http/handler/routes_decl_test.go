// The route declarations of plan P1b: every mounted route declares its keys and scope source (authz.Decl, through
// the protector's Route) next to the legacy gate. Three tests hold them:
//   - TestEveryRouteDeclaresKeys: the ratchet of the routes that declare nothing yet;
//   - TestDeclarationsFollowAppendixA3: each declaration is the one Appendix A.3 of the access spec gives the route
//     (testdata/routes.expected-keys, generated by tools/routekeys);
//   - TestDeclaredKeysMapToTheLegacyGate: the declared keys map back to today's gate through authz/legacy.go.
//
// The rules over the declarations themselves (keys in the catalogue, scope sources, .delete keys, no bare self in the
// staff areas, service routes) are tools/checkroutes, which reads the keys column of routes.golden.

const (
	undeclaredPath   = "testdata/routes.undeclared"
	divergencesPath  = "testdata/routes.legacy-divergences"
	expectedKeysPath = "testdata/routes.expected-keys"

	// maxUndeclared is the number of routes in testdata/routes.undeclared. It only goes down: a PR that declares
	// routes removes them from the list and lowers it by as many; a new route declares from the start. It is 0 at the
	// end of P1b.
	maxUndeclared = 593
)

// readRouteList reads a list of routes with their reasons, one "METHOD /api/path | reason" per line; # starts a
// comment.
func readRouteList(t *testing.T, path string) map[string]string {
	t.Helper()
	b, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read %s: %v", path, err)
	}
	out := map[string]string{}
	for n, line := range strings.Split(string(b), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		id, reason, ok := strings.Cut(line, " | ")
		id = strings.Join(strings.Fields(id), " ")
		if !ok || strings.TrimSpace(reason) == "" || len(strings.Fields(id)) != 2 {
			t.Errorf("%s:%d: want \"METHOD /api/path | reason\", got %q", path, n+1, line)
			continue
		}
		if _, dup := out[id]; dup {
			t.Errorf("%s:%d: %s listed twice", path, n+1, id)
		}
		out[id] = reason
	}
	return out
}

func TestEveryRouteDeclaresKeys(t *testing.T) {
	undeclared := readRouteList(t, undeclaredPath)
	if len(undeclared) != maxUndeclared {
		t.Errorf("%s lists %d routes, maxUndeclared is %d: the list only shrinks, lower the constant with it", undeclaredPath, len(undeclared), maxUndeclared)
	}
	mounted := map[string]bool{}
	for _, s := range buildRoutePolicy(t) {
		id := s.method + " " + s.path
		mounted[id] = true
		_, listed := undeclared[id]
		switch {
		case s.decl == nil && !listed:
			t.Errorf("%s declares no keys: wrap its gate in Route(authz.Decl, gate) per Appendix A.3 of the access spec", id)
		case s.decl != nil && listed:
			t.Errorf("%s declares %s but is still in %s: drop the line (the list only shrinks)", id, s.decl, undeclaredPath)
		}
	}
	for id := range undeclared {
		if !mounted[id] {
			t.Errorf("%s lists %s, which is not mounted", undeclaredPath, id)
		}
	}
}

// expectedDecl is a line of routes.expected-keys.
type expectedDecl struct{ decl, data, source string }

func readExpectedKeys(t *testing.T) map[string]expectedDecl {
	t.Helper()
	b, err := os.ReadFile(expectedKeysPath)
	if err != nil {
		t.Fatalf("read %s: %v", expectedKeysPath, err)
	}
	out := map[string]expectedDecl{}
	for n, line := range strings.Split(string(b), "\n") {
		if strings.TrimSpace(line) == "" || strings.HasPrefix(line, "#") {
			continue
		}
		parts := strings.Split(line, " | ")
		if len(parts) != 4 || !strings.HasPrefix(parts[1], "keys: ") || !strings.HasPrefix(parts[2], "data: ") {
			t.Fatalf("%s:%d: unreadable line %q (regenerate it with tools/routekeys)", expectedKeysPath, n+1, line)
		}
		id := strings.Join(strings.Fields(parts[0]), " ")
		out[id] = expectedDecl{
			decl:   strings.TrimPrefix(parts[1], "keys: "),
			data:   strings.TrimPrefix(parts[2], "data: "),
			source: parts[3],
		}
	}
	return out
}

// TestDeclarationsFollowAppendixA3: a route declares exactly what Appendix A.3 (with tools/routekeys/overrides.txt)
// gives it, so a wrong key that shares today's permission still fails. A row the spec leaves open ("?") cannot be
// declared until it is settled there.
func TestDeclarationsFollowAppendixA3(t *testing.T) {
	expected := readExpectedKeys(t)
	mounted := map[string]bool{}
	for _, s := range buildRoutePolicy(t) {
		id := s.method + " " + s.path
		mounted[id] = true
		e, ok := expected[id]
		switch {
		case !ok:
			t.Errorf("%s has no row in %s: add it to Appendix A.3 of the spec and run tools/routekeys", id, expectedKeysPath)
		case s.decl == nil:
		case e.decl == "?":
			t.Errorf("%s declares %s, but its A.3 row is not settled (%s)", id, s.decl, e.source)
		case s.decl.String() != e.decl:
			t.Errorf("%s declares %s, Appendix A.3 gives %s (%s)", id, s.decl, e.decl, e.source)
		}
	}
	for id := range expected {
		if !mounted[id] {
			t.Errorf("%s lists %s, which is not mounted", expectedKeysPath, id)
		}
	}
}

// TestDeclaredKeysMapToTheLegacyGate: for each declared route, the keys map back (authz.LegacyOf) to the check that
// routes.golden shows today. A key maps when today's permission that decides it gates the route, or when its named
// legacy check is a layer of the route (event.requireManage, ...), or through the platform key that carries it.
// Implicit keys stand for their own permission (self, notifications.self); a public or service route has no real gate;
// a relation is checked behind a self gate. Disagreement is a failure unless testdata/routes.legacy-divergences
// explains it with the A.3 row and the spec section that makes the change.
func TestDeclaredKeysMapToTheLegacyGate(t *testing.T) {
	divergences := readRouteList(t, divergencesPath)
	seen := map[string]bool{}
	for _, s := range buildRoutePolicy(t) {
		if s.decl == nil {
			continue
		}
		id := s.method + " " + s.path
		problem := legacyMismatch(s)
		_, excused := divergences[id]
		if excused {
			seen[id] = true
		}
		switch {
		case problem != "" && !excused:
			t.Errorf("%s: declared %s, legacy gate %v layers %v: %s", id, s.decl, s.gates, s.layers, problem)
		case problem == "" && excused:
			t.Errorf("%s is in %s but its keys map to the legacy gate: drop the line", id, divergencesPath)
		}
	}
	for id := range divergences {
		if !seen[id] {
			t.Errorf("%s lists %s, which is not a declared route", divergencesPath, id)
		}
	}
}

// legacyMismatch explains why the declaration of s does not map back to its legacy gate, or returns "".
func legacyMismatch(s routeSummary) string {
	d := *s.decl
	var real []rbac.Permission
	for _, g := range s.gates {
		if !rbac.RolePublic.HasPermission(g) {
			real = append(real, g)
		}
	}
	var grantable, implicit, public []authz.Key
	for _, k := range d.Keys() {
		spec, ok := authz.Lookup(k)
		switch {
		case !ok:
			return "key " + string(k) + " is not in the catalogue"
		case spec.Allows(authz.ScopeImplicit):
			implicit = append(implicit, k)
		case spec.Allows(authz.ScopePublic):
			public = append(public, k)
		default:
			grantable = append(grantable, k)
		}
	}

	if d.Scope.Kind() == "service" {
		if len(real) > 0 {
			return "a service declaration on a route gated by a user permission"
		}
		return ""
	}
	if d.Scope.Kind() == "public" {
		if len(real) > 0 {
			return "a public declaration on a gated route"
		}
		for _, k := range public {
			if !mapsToGate(k, s.gates, nil) {
				return "public key " + string(k) + " is not today's public gate"
			}
		}
		return ""
	}
	if len(real) == 0 {
		return "the route has no real gate today, but declares " + d.String()
	}

	// Every real gate is explained by a declared key, and every declared key by the gate or a layer. Behind a bare self
	// gate in an area whose check sits in the use case (selfWithoutLayerPrefixes: the exercise policy, the participant
	// use cases), a key maps when a named legacy check decides it: that check is the one the use case runs.
	layers := authzLayers(s)
	inUseCase := len(real) == 1 && real[0] == rbac.PermSelf && len(layers) == 0 && hasPrefix(s.path, selfWithoutLayerPrefixes)
	if inUseCase {
		layers = useCaseChecks
	}
	for _, g := range real {
		explained := false
		for _, k := range d.Keys() {
			l, _ := authz.LegacyOf(k)
			if slices.Contains(l.Permissions, g) || g == rbac.PermSelf && len(grantable) > 0 && mapsToLayer(k, layers) {
				explained = true
			}
		}
		if g == rbac.PermSelf && d.Relation != "" {
			explained = true // the relation is checked behind the self gate, in the use case
		}
		if !explained {
			return "today's gate " + string(g) + " is decided by none of the declared keys"
		}
	}
	for _, k := range append(implicit, grantable...) {
		if !mapsToGate(k, real, layers) {
			return "key " + string(k) + " does not map back to today's gate or layers"
		}
	}
	return ""
}

// useCaseChecks stand for the checks a use case runs behind a bare self gate (every named legacy check but "new").
var useCaseChecks = func() []string {
	var out []string
	for _, c := range authz.LegacyChecks() {
		if c != authz.CheckNew {
			out = append(out, string(c))
		}
	}
	return out
}()

func mapsToGate(k authz.Key, gates []rbac.Permission, layers []string) bool {
	l, ok := authz.LegacyOf(k)
	if !ok {
		return false
	}
	for _, g := range gates {
		if slices.Contains(l.Permissions, g) {
			return true
		}
	}
	if mapsToLayer(k, layers) {
		return true
	}
	for _, carrier := range l.CarriedBy {
		if mapsToGate(carrier, gates, layers) {
			return true
		}
	}
	return false
}

// layerChecks names the legacy checks of layers whose name does not end in their check (spec §2.5): the analytics
// levels of model/eventAnalytics.ResolveAccess, manage and read checks under another name, the authoring checks, and
// the exercise policy closure, which runs AuthorizeExercise with the action of its route.
var layerChecks = map[string][]authz.LegacyCheck{
	"eventAnalytics.requireSections":                     {authz.CheckAnalyticsSections},
	"eventAnalytics.requireSensitive":                    {authz.CheckAnalyticsSensitive},
	"eventAnalytics.requirePeople":                       {authz.CheckAnalyticsPeople},
	"event.requirePreviewCleanup":                        {authz.CheckRequireManage},
	"imageRegistry.requireManageAccess":                  {authz.CheckRequireManage},
	"eventself.(*EventRenderHandler).resolveGrantTenant": {authz.CheckRequireRead},
	"assistant.author":                                   {authz.CheckRequireAuthor},
	"exercise.requireAuthor":                             {authz.CheckRequireAuthor},
	"resourceCalendar.requireTestLabAuthor":              {authz.CheckRequireTestLabAuthor},
	"exercise.authorize.func": {
		authz.CheckAuthorizeExerciseRead, authz.CheckAuthorizeExerciseManage, authz.CheckAuthorizeExerciseFlags,
	},
}

// mapsToLayer: the named legacy check of k is one of the route's layers (event.requireManage → requireManage).
func mapsToLayer(k authz.Key, layers []string) bool {
	l, ok := authz.LegacyOf(k)
	if !ok || l.Check == "" || l.Check == authz.CheckNew {
		return false
	}
	for _, layer := range layers {
		if slices.Contains(layerChecks[layer], l.Check) || strings.HasSuffix(layer, "."+string(l.Check)) || layer == string(l.Check) {
			return true
		}
	}
	return false
}

func TestLegacyMismatchCatchesDisagreement(t *testing.T) {
	decl := func(d authz.Decl) *authz.Decl { return &d }
	cases := []struct {
		name  string
		s     routeSummary
		agree bool
	}{
		{"platform key on its permission", routeSummary{gates: []rbac.Permission{rbac.PermUsersRead}, decl: decl(authz.AnyOf(authz.SourcePlatform, authz.UsersList))}, true},
		{"platform key on another permission", routeSummary{gates: []rbac.Permission{rbac.PermUsersRead}, decl: decl(authz.AnyOf(authz.SourcePlatform, authz.UsersDelete))}, false},
		{"one any-of key off the gate", routeSummary{gates: []rbac.Permission{rbac.PermUsersRead}, decl: decl(authz.AnyOf(authz.SourcePlatform, authz.UsersList, authz.EventsRead))}, false},
		{"own data on self", routeSummary{gates: []rbac.Permission{rbac.PermSelf}, decl: decl(authz.OwnData())}, true},
		{"own data on a permission", routeSummary{gates: []rbac.Permission{rbac.PermUsersRead}, decl: decl(authz.OwnData())}, false},
		{"public flow without a gate", routeSummary{decl: decl(authz.PublicRoute())}, true},
		{"public declaration on a gated route", routeSummary{gates: []rbac.Permission{rbac.PermSelf}, decl: decl(authz.PublicRoute())}, false},
		{"keys on an ungated route", routeSummary{decl: decl(authz.AnyOf(authz.SourcePlatform, authz.UsersList))}, false},
		{"event key on its layer", routeSummary{gates: []rbac.Permission{rbac.PermSelf}, layers: []string{"event.requireManage"}, decl: decl(authz.AnyOf(authz.SourceEventParam("id"), authz.EventSettingsUpdate))}, true},
		{"event key without its layer", routeSummary{gates: []rbac.Permission{rbac.PermSelf}, decl: decl(authz.AnyOf(authz.SourceEventParam("id"), authz.EventSettingsUpdate))}, false},
		{"event key carried by the platform key", routeSummary{gates: []rbac.Permission{rbac.PermEventsWrite}, decl: decl(authz.AnyOf(authz.SourceEventParam("id"), authz.EventsArchive, authz.EventArchive))}, true},
		{"service route without a gate", routeSummary{decl: decl(authz.ServiceRoute(authz.ServiceRender))}, true},
		{"service route behind a permission", routeSummary{gates: []rbac.Permission{rbac.PermSelf}, decl: decl(authz.ServiceRoute(authz.ServiceRender))}, false},
		{"exercise policy in the use case", routeSummary{path: "/api/exercises/:id", gates: []rbac.Permission{rbac.PermSelf}, decl: decl(authz.AnyOf(authz.SourceObject("exercise"), authz.ExercisesUpdate))}, true},
		{"no use-case check outside its areas", routeSummary{path: "/api/users/:userID", gates: []rbac.Permission{rbac.PermSelf}, decl: decl(authz.AnyOf(authz.SourcePlatform, authz.UsersRead))}, false},
		{"exercise policy closure as a layer", routeSummary{gates: []rbac.Permission{rbac.PermSelf}, layers: []string{"exercise.authorize.func"}, decl: decl(authz.AnyOf(authz.SourceObject("exercise"), authz.ExercisesRead))}, true},
		{"relation behind self", routeSummary{gates: []rbac.Permission{rbac.PermSelf}, decl: decl(authz.Related(authz.SourceTenant, authz.RelParticipant))}, true},
	}
	for _, c := range cases {
		got := legacyMismatch(c.s)
		if (got == "") != c.agree {
			t.Errorf("%s: legacyMismatch = %q, want agreement %v", c.name, got, c.agree)
		}
	}
}

// The probe sees through Route: a permission gate is a gate, and anything else passed as legacy comes back to be
// recorded as a layer (and failed by buildRoutePolicy).
func TestProbeTellsAGateFromAnotherCheckInsideRoute(t *testing.T) {
	decl := authz.AnyOf(authz.SourcePlatform, authz.UsersList)
	gate, d, legacy, _ := probe(probeProtector{}.Route(decl, probeProtector{}.RequirePermission(rbac.PermUsersRead)))
	if gate == nil || *gate != rbac.PermUsersRead || d == nil || legacy != nil {
		t.Errorf("Route around a gate: gate %v decl %v legacy set %v", gate, d, legacy != nil)
	}
	check := func(c *gin.Context) { c.Next() }
	gate, d, legacy, _ = probe(probeProtector{}.Route(decl, check))
	if gate != nil || d == nil || legacy == nil {
		t.Errorf("Route around another check: gate %v decl %v legacy set %v", gate, d, legacy != nil)
	}
	gate, d, legacy, _ = probe(probeProtector{}.Route(authz.PublicRoute(), nil))
	if gate != nil || d == nil || legacy != nil {
		t.Errorf("Route without a gate: gate %v decl %v legacy set %v", gate, d, legacy != nil)
	}
}
